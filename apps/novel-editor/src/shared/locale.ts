export function uiText(locale: AppLocale, japanese: string): string {
  if (locale !== "en") return japanese;
  const direct = ENGLISH_UI[japanese];
  if (direct !== undefined) return direct;
  const download = /^(.+) をダウンロードしています…(?: (\d+)%)?$/u.exec(japanese);
  if (download !== null) return `Downloading ${download[1]}…${download[2] === undefined ? "" : ` ${download[2]}%`}`;
  const deviceCode = /^GitHubのdevice code: (.+)（clipboardにもコピー済み）$/u.exec(japanese);
  if (deviceCode !== null) return `GitHub device code: ${deviceCode[1]} (also copied to the clipboard)`;
  const httpError = /^(OpenAI API|GitHub Releases)(?:が処理を完了|へ接続|を確認)できませんでした（HTTP (\d+)）。$/u.exec(japanese);
  if (httpError !== null) return `${httpError[1]} request failed (HTTP ${httpError[2]}).`;
  const launchError = /^installerを起動できませんでした: (.+)$/u.exec(japanese);
  if (launchError !== null) return `Could not start the installer: ${launchError[1]}`;
  const codexTimeout = /^Codexの(.+)が時間切れになりました。$/u.exec(japanese);
  if (codexTimeout !== null) return `The Codex ${codexTimeout[1]} request timed out.`;
  const codexExit = /^Codex App Serverが終了しました（(-?\d+)）。$/u.exec(japanese);
  if (codexExit !== null) return `Codex App Server exited (${codexExit[1]}).`;
  return japanese;
}

export function commandLabel(definition: CommandDefinition, locale: AppLocale): string {
  return locale === "en" ? ENGLISH_COMMANDS[definition.id] : definition.label;
}

export function commandCategory(definition: CommandDefinition, locale: AppLocale): string {
  return uiText(locale, definition.category);
}
